------------------------------ macOS-style keys --------------------------
-- ⌘ = SUPER. App shortcuts like ⌘C/⌘V are left to applications.
hl.bind("SUPER + Space", hl.dsp.exec_cmd("creed toggle launcher"), { description = "Spotlight" })
hl.bind("SUPER + Q", hl.dsp.window.close(), { description = "Quit" })
hl.bind("SUPER + W", hl.dsp.window.close(), { description = "Close window" })
hl.bind("SUPER + M", hl.dsp.window.move({ workspace = "special:minimized" }), { description = "Minimise" })
hl.bind("SUPER + H", hl.dsp.window.move({ workspace = "special:hidden" }), { description = "Hide" })
hl.bind("SUPER + Tab", hl.dsp.window.cycle_next(), { description = "App switcher" })
hl.bind("CTRL + up", hl.dsp.exec_cmd("creed toggle overview"), { description = "Mission Control" })
hl.bind("SUPER + F3", hl.dsp.exec_cmd("creed toggle overview"), { description = "Mission Control" })
hl.bind("SUPER + F4", hl.dsp.exec_cmd("creed toggle launchpad"), { description = "Launchpad" })
hl.bind("CTRL + left", hl.dsp.focus({ workspace = "e-1" }), { description = "Space left" })
hl.bind("CTRL + right", hl.dsp.focus({ workspace = "e+1" }), { description = "Space right" })
hl.bind("SUPER + CTRL + F", hl.dsp.window.fullscreen({ mode = "fullscreen" }), { description = "Full screen" })
hl.bind("SUPER + CTRL + Q", hl.dsp.exec_cmd("loginctl lock-session"), { description = "Lock screen" })
hl.bind("SUPER + SHIFT + 3", hl.dsp.exec_cmd("creed screenshot screen"), { description = "Screenshot" })
hl.bind("SUPER + SHIFT + 4", hl.dsp.exec_cmd("creed screenshot region"), { description = "Screenshot area" })
hl.bind("SUPER + SHIFT + Q", hl.dsp.exec_cmd("creed toggle power"), { description = "Log out…" })
hl.bind("SUPER + comma", hl.dsp.exec_cmd("creed-settings"), { description = "Settings" })
hl.bind("SUPER + N", hl.dsp.exec_cmd("creed toggle notif-center"), { description = "Notification Center" })
hl.bind("SUPER + Return", hl.dsp.exec_cmd("{{ app.terminal }}"), { description = "Terminal" })
hl.bind("SUPER + E", hl.dsp.exec_cmd("{{ app.file_manager }}"), { description = "Finder" })
hl.bind("SUPER + T", hl.dsp.window.float({ action = "toggle" }), { description = "Float / tile" })
